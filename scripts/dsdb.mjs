// Datasheet DB. Source of truth: datasheets/records/<slug>.json — one structured record per part (schema in src/parts/dsrec.js)
//   node scripts/dsdb.mjs          → validates every record, renders datasheets/db/<slug>.html (generated pages),
//                                    bundles src/parts/dsdb.js (records, embedded in dist/index.html), src/parts/dskey.js
//                                    (the generator's candidate figures: key.spec / key.grade) and datasheets/db/index.json
//   node scripts/dsdb.mjs --init   → also writes a stub record for every part in src/parts/parts.js that has none yet
// A record with validation errors stops the build (min > max, duplicate pin numbers, bad status …); warnings are listed.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, unlinkSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dbDir = join(root, 'datasheets/db'), recDir = join(root, 'datasheets/records');
mkdirSync(dbDir, { recursive: true }); mkdirSync(recDir, { recursive: true });
const load = (f, name) => { const ctx = vm.createContext({ console }); vm.runInContext(readFileSync(join(root, f), 'utf8').replace(/if ?\(typeof module[^;]+;/, ''), ctx); return vm.runInContext(name, ctx); };
const PARTS = load('src/parts/parts.js', 'PARTS'), DSREC = load('src/parts/dsrec.js', 'DSREC');
const init = process.argv.includes('--init');
const slug = DSREC.slug;

function stub(mpn, p) {
  const price = PARTS.price(mpn, p.cat);
  const links = PARTS.links(p, mpn).map(([t, u]) => `<a href="${u}" target="_blank" rel="noopener">${t}</a>`).join(' · ');
  return { mpn, mfr: p.mfr || '', cat: p.cat || '', price: price != null ? price : null, status: 'stub', title: p.title || '',
    meta: [`${p.mfr} · ${p.cat || ''} · ${p.title}${price != null ? ` · 참고 단가 약 $${price} (추정)` : ''}`, `원본: ${links || '(링크 없음)'}`],
    todo: '이 레코드는 부품 DB의 요약으로 만든 초안입니다. 실제 데이터시트를 보고 채운 뒤 status를 "done"으로 바꾸세요.',
    sections: [{ h: '핵심 사양', blocks: [{ dl: (p.specs || []).map(([k, v]) => [k, String(v)]) }] }] };
}
if (init) {
  let n = 0;
  Object.entries(PARTS.P).forEach(([mpn, p]) => {
    const f = join(recDir, slug(mpn) + '.json');
    if (existsSync(f)) return;
    writeFileSync(f, JSON.stringify(stub(mpn, p), null, 1) + '\n');
    n++;
  });
  console.log(`stub records written: ${n}`);
}

// validate → render pages → bundle
const items = {}, keys = {}; let nErr = 0, nWarn = 0;
readdirSync(recDir).filter((f) => f.endsWith('.json')).sort().forEach((f) => {
  let r; try { r = JSON.parse(readFileSync(join(recDir, f), 'utf8')); } catch (e) { console.error(`✗ ${f}: JSON — ${e.message}`); nErr++; return; }
  const v = DSREC.validate(r);
  v.errors.forEach((e) => console.error(`✗ ${r.mpn || f}: ${e}`)); v.warnings.forEach((w) => console.warn(`  ${r.mpn || f}: ${w}`));
  nErr += v.errors.length; nWarn += v.warnings.length;
  if (slug(r.mpn) + '.json' !== f) console.warn(`  ${f}: file name should be ${slug(r.mpn)}.json`);
  writeFileSync(join(dbDir, slug(r.mpn) + '.html'), DSREC.page(r));
  items[r.mpn] = { file: 'datasheets/db/' + slug(r.mpn) + '.html', mfr: r.mfr, cat: r.cat, price: r.price, status: r.status, alias: r.alias && r.alias.length ? r.alias.join(' ') : undefined, src: r.src && r.src.length ? r.src.join(' ') : undefined, title: r.title, rec: r };
  if (r.key) { const { mpn: cand, ...k } = r.key; if (keys[cand || r.mpn]) console.warn(`  ${r.mpn}: key for ${cand || r.mpn} given twice`); keys[cand || r.mpn] = k; }
});
if (nErr) { console.error(`dsdb: ${nErr} validation error(s) — fix the records above`); process.exit(1); }
// pages whose record is gone (renamed or deleted part) would linger as stale pages
readdirSync(dbDir).filter((f) => f.endsWith('.html') && !Object.values(items).some((v) => v.file === 'datasheets/db/' + f)).forEach((f) => { unlinkSync(join(dbDir, f)); console.log(`  removed stale page datasheets/db/${f}`); });
const built = new Date().toISOString().slice(0, 10);
writeFileSync(join(dbDir, 'index.json'), JSON.stringify({ built, items: Object.fromEntries(Object.entries(items).map(([k, v]) => [k, { file: v.file, mfr: v.mfr, cat: v.cat, price: v.price, status: v.status, alias: v.alias, title: v.title }])) }, null, 2));
const js = `/* generated by scripts/dsdb.mjs from datasheets/records/*.json — do not edit; edit the records and rebuild */
const DSDB=${JSON.stringify({ built, items })};
if(typeof module!=='undefined')module.exports=DSDB;
`;
writeFileSync(join(root, 'src/parts/dsdb.js'), js);
const kjs = `/* generated by scripts/dsdb.mjs: the generator's candidate figures (record.key) — do not edit; edit datasheets/records */
const DSKEY=${JSON.stringify(keys)};
if(typeof module!=='undefined')module.exports=DSKEY;
`;
writeFileSync(join(root, 'src/parts/dskey.js'), kjs);
const st = {}; Object.values(items).forEach((v) => { st[v.status] = (st[v.status] || 0) + 1; });
console.log(`dsdb: ${Object.keys(items).length} records (${Object.entries(st).map(([k, n]) => k + ' ' + n).join(' · ')}) · ${nWarn} warnings → src/parts/dsdb.js (${(js.length / 1024).toFixed(0)} KB), dskey.js (${Object.keys(keys).length} parts), datasheets/db/*.html`);
