#!/bin/sh
# Compiles src/route/kernel.c to WebAssembly and writes it as base64 into src/route/kernel.b64.js (checked in, so the
# app build and the tests need no C toolchain). Needs clang with the wasm32 target and wasm-ld (LLVM ≥ 15).
set -e
cd "$(dirname "$0")/.."
clang --target=wasm32 -O3 -nostdlib -fno-builtin-memset -Wl,--no-entry -Wl,--import-memory -Wl,--initial-memory=65536 -Wl,-z,stack-size=8192 \
  -Wl,--export=astar -Wl,--export=paint -Wl,--export=__heap_base -o /tmp/kernel.wasm src/route/kernel.c
printf '/* generated by scripts/build-wasm.sh from src/route/kernel.c — the routing kernels (A* · paint) as WebAssembly */\nconst AUTOROUTE_WASM_B64=%s;\n' "\"$(base64 -w0 /tmp/kernel.wasm)\"" > src/route/kernel.b64.js
ls -la /tmp/kernel.wasm src/route/kernel.b64.js
